import { z } from "zod";

export const CATEGORIES = [
  "คอมพิวเตอร์",
  "เครือข่าย",
  "ไมโครคอนโทรลเลอร์",
  "อุปกรณ์ต่อพ่วง",
  "เครื่องมือช่าง",
  "เครื่องเสียงและดนตรี",
  "เกมและหนังสือ",
  "อุปกรณ์ศิลปะ",
  "ของใช้ทั่วไป",
  "อื่นๆ",
] as const;

export const itemSchema = z.object({
  name: z
    .string()
    .trim()
    .min(1, "กรุณากรอกชื่ออุปกรณ์")
    .max(100, "ชื่ออุปกรณ์ต้องไม่เกิน 100 ตัวอักษร"),

  category: z.enum(CATEGORIES, { error: "กรุณาเลือกหมวดหมู่" }),

  description: z
    .string()
    .trim()
    .max(500, "รายละเอียดต้องไม่เกิน 500 ตัวอักษร")
    .optional(),

  totalQty: z
    .number({ error: "กรุณากรอกจำนวนเป็นตัวเลข" })
    .int("จำนวนต้องเป็นจำนวนเต็ม")
    .min(1, "จำนวนต้องไม่น้อยกว่า 1")
    .max(1000, "จำนวนต้องไม่เกิน 1000"),
});